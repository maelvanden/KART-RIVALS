// Run with PGLITE_MODULE pointing to an installed @electric-sql/pglite module.
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema auth;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to authenticated;
grant execute on function auth.uid() to authenticated;
create table public.profiles(id uuid primary key,banned_at timestamptz,is_demo boolean not null default false);
insert into profiles(id) values('00000000-0000-0000-0000-000000000001'),('00000000-0000-0000-0000-000000000002');
`);
await db.exec(await readFile(new URL('../supabase/migrations/20261224000084_discord_account_links.sql',import.meta.url),'utf8'));
const p1='00000000-0000-0000-0000-000000000001',p2='00000000-0000-0000-0000-000000000002';
const d1='111111111111111111',d2='222222222222222222';
const asUser=async(p)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[p]);await db.exec('set role authenticated');};
const service=async()=>db.exec('reset role; set role service_role');
const rpc=async(sql,params=[])=>(await db.query('select '+sql+' as result',params)).rows[0].result;
await asUser(p1);
assert.deepEqual(await rpc('my_discord_link()'),{});
const code=(await rpc('create_discord_link_code()')).code;
assert.match(code,/^[A-F0-9]{32}$/);
await assert.rejects(()=>rpc('create_discord_link_code()'),/30 secondes/);
await assert.rejects(()=>db.query('select * from discord_link_codes'),/permission denied/);
await assert.rejects(()=>rpc('redeem_discord_link($1,$2)',[d1,code]),/permission denied/);
await service();
assert.equal((await rpc('redeem_discord_link($1,$2)',[d1,'BAD'])).status,'invalid');
assert.equal((await rpc('redeem_discord_link($1,$2)',[d1,code.toLowerCase()])).status,'linked');
assert.equal((await rpc('redeem_discord_link($1,$2)',[d2,code])).status,'invalid','code is single-use');
assert.equal((await rpc('discord_linked_profile($1)',[d1])).profile_id,p1);
await asUser(p2);assert.deepEqual(await rpc('my_discord_link()'),{});
await rpc('unlink_my_discord()');
await asUser(p1);assert.equal((await rpc('my_discord_link()')).discord_id,d1);
await assert.rejects(()=>rpc('create_discord_link_code()'),/Dissocie/);
await rpc('unlink_my_discord()');assert.deepEqual(await rpc('my_discord_link()'),{});
const expired=(await rpc('create_discord_link_code()')).code;
await db.exec("reset role; update discord_link_codes set expires_at=now()-interval '1 second',created_at=now()-interval '1 minute'");
await service();assert.equal((await rpc('redeem_discord_link($1,$2)',[d2,expired])).status,'invalid');
await asUser(p1);const fresh=(await rpc('create_discord_link_code()')).code;
await service();assert.equal((await rpc('redeem_discord_link($1,$2)',[d2,expired])).status,'invalid');
assert.equal((await rpc('redeem_discord_link($1,$2)',[d2,fresh])).status,'linked');
await asUser(p2);const other=(await rpc('create_discord_link_code()')).code;
await service();assert.equal((await rpc('redeem_discord_link($1,$2)',[d2,other])).status,'already_linked');
await rpc('unlink_discord_account($1)',[d2]);
assert.deepEqual(await rpc('discord_linked_profile($1)',[d2]),{});
// Exhausting failed attempts prevents guessing even a valid code during that window.
for(let n=0;n<5;n++) await rpc('redeem_discord_link($1,$2)',['333333333333333333','bad']);
assert.equal((await rpc('redeem_discord_link($1,$2)',['333333333333333333',other])).status,'limited');
await db.exec("reset role; update profiles set banned_at=now() where id='"+p2+"'");
await service();assert.equal((await rpc('redeem_discord_link($1,$2)',['444444444444444444',other])).status,'invalid');
await db.exec('reset role; set role anon');
await assert.rejects(()=>rpc('create_discord_link_code()'),/permission denied/);
await assert.rejects(()=>rpc('my_discord_link()'),/permission denied/);
await assert.rejects(()=>rpc('unlink_discord_account($1)',[d1]),/permission denied/);
console.log('Discord linking SQL: ownership, permissions, expiry, rotation, replay, unlink and rate limits passed.');
await db.close();
